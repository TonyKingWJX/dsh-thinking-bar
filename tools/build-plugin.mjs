import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(process.cwd())
const assetsDir = path.join(root, 'preview', 'assets')
const assetFiles = [
  'whale-bg.webp',
  'whale-0.webp',
  'whale-1.webp',
  'whale-2.webp',
  'whale-3.webp',
  'whale-4.webp',
  'whale-5.webp',
  'whale-6.webp',
  'liang-hero-0.webp',
  'liang-hero-1.webp',
  'liang-hero-2.webp',
  'liang-hero-3.webp',
  'liang-hero-4.webp',
  'liang-hero-5.webp',
  'liang-hero-6.webp',
  'liang-bg-0.webp',
  'liang-bg-1.webp',
  'liang-bg-2.webp',
  'liang-bg-3.webp',
  'liang-bg-4.webp',
  'liang-bg-5.webp',
  'liang-bg-6.webp'
]

const assets = {}
for (const file of assetFiles) {
  const full = path.join(assetsDir, file)
  assets[file] = 'data:image/webp;base64,' + fs.readFileSync(full).toString('base64')
}

const core = fs.readFileSync(path.join(root, 'lib', 'ui.js'), 'utf8')
const body = fs.readFileSync(path.join(root, 'plugin-client-body.js'), 'utf8')

const output =
  `/* dsh-thinking-bar client bundle — generated by tools/build-plugin.mjs */\n` +
  `window.__ModuleLoader__.load({\n` +
  `  id: 'dsh-thinking-bar',\n` +
  `  factory(require) {\n` +
  `    'use strict';\n` +
  `    const React = require('react');\n` +
  `    const h = React.createElement;\n` +
  `    /* ---- shared thinking-bar UI core (kept in sync with preview/lib/ui.js) ---- */\n` +
  core +
  `\n    /* ---- inlined theme assets ---- */\n` +
  `    const ASSETS = ${JSON.stringify(assets)};\n` +
  `    /* ---- plugin client body ---- */\n` +
  body +
  `\n  }\n` +
  `});\n`

fs.writeFileSync(path.join(root, 'client.js'), output)
console.log('client.js written:', output.length, 'chars;', assetFiles.length, 'assets inlined')
